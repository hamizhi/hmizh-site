-- Order workflow:
-- pending -> paid -> delivering -> delivered
-- canceled is kept as the terminal cancellation state.

alter table public.orders
  add column if not exists id bigint generated by default as identity,
  add column if not exists client_ip text,
  add column if not exists updated_at timestamptz not null default now();

update public.orders
   set status = 'canceled'
 where status in ('failed', 'refunded');

alter table public.orders
  drop constraint if exists orders_status_check;

alter table public.orders
  add constraint orders_status_check
  check (status in ('pending', 'paid', 'delivering', 'delivered', 'canceled'));

create index if not exists orders_id_idx on public.orders(id);
create index if not exists orders_updated_at_idx on public.orders(updated_at desc);

create or replace function public.set_orders_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists orders_set_updated_at on public.orders;

create trigger orders_set_updated_at
before update on public.orders
for each row
execute function public.set_orders_updated_at();

-- Payment callbacks only confirm payment. Card assignment is intentionally
-- deferred until an administrator moves the order to delivered.
create or replace function public.mark_order_paid(
  p_order_id text,
  p_trade_no text,
  p_money numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  select *
    into v_order
    from public.orders
   where order_id = p_order_id
   for update;

  if not found then
    raise exception 'order_not_found';
  end if;

  if v_order.money <> p_money then
    raise exception 'amount_mismatch';
  end if;

  if v_order.status = 'pending' then
    update public.orders
       set status = 'delivering',
           provider_trade_no = coalesce(provider_trade_no, p_trade_no),
           provider = 'luckywood',
           paid_at = coalesce(paid_at, now())
     where order_id = v_order.order_id;

    return jsonb_build_object(
      'status', 'delivering',
      'card_code', null
    );
  end if;

  return jsonb_build_object(
    'status', v_order.status,
    'card_code', v_order.card_code
  );
end;
$$;

revoke all on function public.mark_order_paid(text, text, numeric)
from public, anon, authenticated;

grant execute on function public.mark_order_paid(text, text, numeric)
to service_role;

-- Assign exactly one unused card while holding the order lock. Repeated
-- requests are idempotent and return the already assigned card.
create or replace function public.mark_order_delivered(
  p_order_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_card public.card_keys%rowtype;
  v_stock_plan_id text;
begin
  select *
    into v_order
    from public.orders
   where order_id = p_order_id
   for update;

  if not found then
    raise exception 'order_not_found';
  end if;

  if v_order.status = 'delivered' then
    return jsonb_build_object(
      'status', 'delivered',
      'card_code', v_order.card_code
    );
  end if;

  -- Orders created by the previous implementation may already have a card.
  -- Do not consume a second card when an administrator completes them.
  if v_order.card_code is not null then
    update public.orders
       set status = 'delivered'
     where order_id = v_order.order_id;

    return jsonb_build_object(
      'status', 'delivered',
      'card_code', v_order.card_code
    );
  end if;

  if v_order.status not in ('paid', 'delivering') then
    raise exception 'invalid_delivery_status';
  end if;

  v_stock_plan_id := replace(v_order.plan_id, '-', '_');

  select *
    into v_card
    from public.card_keys
   where plan_id = v_stock_plan_id
     and is_used = 0
   order by created_at asc, id asc
   for update skip locked
   limit 1;

  if not found then
    raise exception 'out_of_stock';
  end if;

  update public.card_keys
     set is_used = 1,
         order_id = v_order.order_id
   where id = v_card.id;

  update public.orders
     set status = 'delivered',
         card_code = v_card.card_code
   where order_id = v_order.order_id;

  return jsonb_build_object(
    'status', 'delivered',
    'card_code', v_card.card_code
  );
end;
$$;

revoke all on function public.mark_order_delivered(text)
from public, anon, authenticated;

grant execute on function public.mark_order_delivered(text)
to service_role;
